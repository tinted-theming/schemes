#!/usr/bin/env node
// Regenerate the GitHub base16 / base24 schemes from @primer/primitives.
//
// Sources (single pinned npm dependency, see package.json):
//   - Grays (base00..07) + black/white  ->  src json5 `base.color.neutral.*`
//     (the literal "neutral scale"), resolved per theme through the
//     parent + @extends override file chain, following {ref} pointers.
//   - Accents (base08..0F, base12..17)  ->  the already-resolved CSS custom
//     properties in dist (`--ansi-*` etc.), which bake in all per-variant
//     (dimmed / high-contrast / colorblind) layering for us.
//
// Everything below the CONFIG block is mechanical; tune the CONFIG to change
// which upstream color feeds which scheme slot.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import JSON5 from 'json5'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const PKG = path.join(ROOT, 'node_modules', '@primer', 'primitives')
const SRC = path.join(PKG, 'src', 'tokens', 'base', 'color')
const DOCS = path.join(PKG, 'dist', 'docs', 'functional', 'themes')
const AUTHOR = 'Tinted Theming (https://github.com/tinted-theming)'

// Prepended to every generated scheme so hand edits aren't lost on regeneration.
// Stamps the exact @primer/primitives revision this run sourced from.
const PRIMER_VERSION = JSON.parse(fs.readFileSync(path.join(PKG, 'package.json'), 'utf8')).version
const HEADER = `# DO NOT EDIT BY HAND.
# Generated by scripts/generate-github-schemes.mjs, with color values pulled from
# @primer/primitives v${PRIMER_VERSION} (GitHub's upstream design tokens).
# Re-run the generator to update.

`

// ─────────────────────────────────────────────────────────────────────────
// CONFIG
// ─────────────────────────────────────────────────────────────────────────

// The 7 GitHub themes we generate. `theme` is both the primer dist CSS file
// name AND (for non-default themes) the override key. `base` is the src json5
// neutral file chain (parent first, override last).
const THEMES = [
  { file: 'github',                       name: 'Github',                       variant: 'light', theme: 'light',               base: ['light/light'] },
  { file: 'github-dark',                  name: 'Github Dark',                  variant: 'dark',  theme: 'dark',                base: ['dark/dark'] },
  { file: 'github-light-high-contrast',   name: 'Github Light High Contrast',   variant: 'light', theme: 'light-high-contrast', base: ['light/light', 'light/light.high-contrast'] },
  { file: 'github-dark-high-contrast',    name: 'Github Dark High Contrast',    variant: 'dark',  theme: 'dark-high-contrast',  base: ['dark/dark', 'dark/dark.high-contrast'] },
  { file: 'github-dark-dimmed',           name: 'Github Dark Dimmed',           variant: 'dark',  theme: 'dark-dimmed',         base: ['dark/dark', 'dark/dark.dimmed'] },
  { file: 'github-light-colorblind',      name: 'Github Light Colorblind',      variant: 'light', theme: 'light-colorblind',    base: ['light/light'] },
  { file: 'github-dark-colorblind',       name: 'Github Dark Colorblind',       variant: 'dark',  theme: 'dark-colorblind',     base: ['dark/dark'] },
]

// base00..07 monotone ramp = these neutral-scale steps (bg -> fg), per polarity.
// Light goes lightest..darkest; dark goes darkest..lightest.
const MONO_STEPS = {
  light: [0, 1, 6, 8, 9, 10, 12, 13],
  dark:  [1, 2, 6, 8, 9, 11, 12, 13],
}

// Accent slots -> resolved primer token name (key in the docs JSON). Affects
// only base16/base24 accents; tinted8 has its own maps and ignores this.
// Two philosophies, selectable with `--mode`:
//
//   ansi  (default) — map GitHub's *terminal* (ANSI) palette by hue
//     (base08=red, etc). Matches GitHub's terminal colors; the editor view
//     diverges. This is what the committed GitHub base16/base24 schemes ship.
//
//   prettylights — map GitHub's *code syntax* (prettylights) colors onto
//     base16's semantic roles, so a base16 highlighter reproduces GitHub's
//     editor view. The original "match GitHub code highlighting" goal.
//
// Neither GitHub palette defines a "class" gold (base0A) — both fall back to
// ANSI yellow (brown in light, gold in dark) and it's flagged. The base24
// bright slots have no syntax/prettylights analogue, so they always use ANSI
// bright variants.
const BRIGHTS = {
  base12: 'ansi-redBright',
  base13: 'ansi-yellowBright',
  base14: 'ansi-greenBright',
  base15: 'ansi-cyanBright',
  base16: 'ansi-blueBright',
  base17: 'ansi-magentaBright',
}
const ACCENT_MODES = {
  prettylights: {
    base08: 'prettylights-syntax-variable',   // variables
    base09: 'prettylights-syntax-constant',   // constants / numbers
    base0A: 'fgColor-attention',               // classes — GitHub 'attention' gold (no true syntax eqv)
    base0B: 'prettylights-syntax-string',     // strings
    base0C: 'prettylights-syntax-stringRegexp',// regex / escapes
    base0D: 'prettylights-syntax-entity',     // functions / entities
    base0E: 'prettylights-syntax-keyword',    // keywords
    base0F: 'prettylights-syntax-bracketHighlighterUnmatched',
    ...BRIGHTS,
  },
  ansi: {
    base08: 'ansi-red',
    base09: 'prettylights-syntax-variable',   // orange — ANSI has none
    base0A: 'fgColor-attention',               // GitHub 'attention' gold
    base0B: 'ansi-green',
    base0C: 'ansi-cyan',
    base0D: 'ansi-blue',
    base0E: 'ansi-magenta',
    base0F: 'ansi-redBright',
    ...BRIGHTS,
  },
}
const MODE = (process.argv.find((a) => a.startsWith('--mode='))?.split('=')[1]) || 'ansi'
if (!ACCENT_MODES[MODE]) { console.error(`unknown --mode=${MODE} (use prettylights|ansi)`); process.exit(1) }
const ACCENT_VARS = ACCENT_MODES[MODE]

const BASE16_SLOTS = ['base00','base01','base02','base03','base04','base05','base06','base07',
                      'base08','base09','base0A','base0B','base0C','base0D','base0E','base0F']
const BASE24_SLOTS = [...BASE16_SLOTS,
                      'base10','base11','base12','base13','base14','base15','base16','base17']

// ── Tinted8 ───────────────────────────────────────────────────────────────
// Tinted8 carries GitHub's three color domains on the right semantic keys:
//   palette  <- ANSI  (terminal fidelity + the accent hues)
//   syntax.* <- prettylights  (blob/gist parity)
//   ui.*     <- functional tokens  (correct canvas/chrome — ANSI ink is NOT
//              the editor surface, so palette defaults would mis-colour it)
// Only solid #RRGGBB tokens are used; GitHub's alpha tokens (selection,
// neutral-muted, accent-muted in dark, ...) are skipped — Tinted8 forbids
// alpha, and the builder defaults those keys acceptably. Keys are sparse:
// unspecified keys inherit/derive per the Tinted8 builder spec.
const T8_PALETTE = {
  black: 'ansi-black',   red: 'ansi-red',         green: 'ansi-green',     yellow: 'ansi-yellow',
  blue: 'ansi-blue',     magenta: 'ansi-magenta', cyan: 'ansi-cyan',       white: 'ansi-white',
  'black-bright': 'ansi-blackBright',   'red-bright': 'ansi-redBright',     'green-bright': 'ansi-greenBright',
  'yellow-bright': 'ansi-yellowBright', 'blue-bright': 'ansi-blueBright',   'magenta-bright': 'ansi-magentaBright',
  'cyan-bright': 'ansi-cyanBright',     'white-bright': 'ansi-whiteBright',
  gray: 'ansi-gray',     orange: 'prettylights-syntax-variable',
}
const T8_SYNTAX = {
  'comment': 'prettylights-syntax-comment',
  'keyword': 'prettylights-syntax-keyword',
  'storage': 'prettylights-syntax-keyword',            // GitHub colours storage as keyword
  'keyword.control.import': 'prettylights-syntax-storageModifierImport',
  'string': 'prettylights-syntax-string',
  'string.regexp': 'prettylights-syntax-stringRegexp',
  'constant': 'prettylights-syntax-constant',
  'variable': 'prettylights-syntax-variable',
  'variable.parameter': 'fgColor-default',             // GitHub leaves params default-coloured
  'entity.name.function': 'prettylights-syntax-entity',
  'support.function': 'prettylights-syntax-entity',    // builtins render as entities on GitHub
  'entity.name.tag': 'prettylights-syntax-entityTag',
  'entity.name.namespace': 'prettylights-syntax-variable',
  'punctuation': 'fgColor-default',                    // GitHub leaves punctuation uncoloured
  'markup.bold': 'prettylights-syntax-markup-bold',
  'markup.italic': 'prettylights-syntax-markup-italic',
  'markup.heading': 'prettylights-syntax-markup-heading',
  'markup.list': 'prettylights-syntax-markup-list',
  'markup.link': 'prettylights-syntax-constantOtherReferenceLink',
  'markup.inserted': 'prettylights-syntax-markup-inserted-text',
  'markup.changed': 'prettylights-syntax-markup-changed-text',
  'markup.deleted': 'prettylights-syntax-markup-deleted-text',
}
const T8_UI = {
  'global.background.normal': 'bgColor-default',
  'global.background.dark': 'bgColor-muted',
  'global.foreground.normal': 'fgColor-default',
  'global.foreground.dark': 'fgColor-muted',
  'chrome.background.normal': 'bgColor-muted',
  'chrome.foreground.normal': 'fgColor-default',
  'chrome.foreground.dark': 'fgColor-muted',
  'border.normal': 'borderColor-default',
  'accent.normal': 'fgColor-accent',
  // Styling spec defines the leaves `ui.link.normal.{foreground,background}`,
  // not a bare `ui.link.normal` (that bare form in the builder spec's defaults
  // table is a doc bug the builder rejects). Use the foreground leaf.
  'link.normal.foreground': 'fgColor-accent',
  'gutter.background': 'bgColor-default',
  'gutter.foreground': 'fgColor-disabled',
  'whitespace.foreground': 'fgColor-disabled',
  // GitHub has no dedicated caret token: caret = default fg, char-under-caret =
  // canvas (sourcing foreground from functional avoids the ANSI-white=gray trap).
  // Cursor keys are state-first (`cursor.<state>.<ground>`), like link — the
  // spec tables' ground-first `cursor.background.normal` form is a doc bug.
  'cursor.normal.background': 'fgColor-default',
  'cursor.normal.foreground': 'bgColor-default',
  'cursor.muted.background': 'fgColor-muted',
  'cursor.muted.foreground': 'bgColor-muted',
  'status.error': 'fgColor-danger',
  'status.warning': 'fgColor-attention',
  'status.success': 'fgColor-success',
  'status.info': 'fgColor-accent',
  'tooltip.background': 'bgColor-emphasis',
  'tooltip.foreground': 'fgColor-onEmphasis',
}

// ─────────────────────────────────────────────────────────────────────────
// src json5 neutral-scale resolver
// ─────────────────────────────────────────────────────────────────────────

function deepMerge(target, source) {
  for (const k of Object.keys(source)) {
    if (source[k] && typeof source[k] === 'object' && !Array.isArray(source[k]) &&
        target[k] && typeof target[k] === 'object') {
      deepMerge(target[k], source[k])
    } else {
      target[k] = source[k]
    }
  }
  return target
}

// Returns base.color.* tree for a theme (parent merged with @extends overrides).
function loadColorTree(baseChain) {
  const tree = {}
  for (const rel of baseChain) {
    const file = path.join(SRC, `${rel}.json5`)
    const parsed = JSON5.parse(fs.readFileSync(file, 'utf8'))
    deepMerge(tree, parsed.base.color)
  }
  return tree
}

// Resolve a base.color dotted path (e.g. "neutral.9", "black") to a hex string.
function resolveColor(tree, dottedPath, seen = new Set()) {
  if (seen.has(dottedPath)) throw new Error(`ref cycle at ${dottedPath}`)
  seen.add(dottedPath)
  let node = tree
  for (const part of dottedPath.split('.')) node = node?.[part]
  if (!node || !('$value' in node)) throw new Error(`missing token base.color.${dottedPath}`)
  const v = node.$value
  if (typeof v === 'object' && v.hex) return v.hex
  if (typeof v === 'string') {
    const m = v.match(/^\{base\.color\.(.+)\}$/)
    if (!m) throw new Error(`unexpected ref ${v}`)
    return resolveColor(tree, m[1], seen)
  }
  throw new Error(`unresolvable $value for base.color.${dottedPath}`)
}

// ─────────────────────────────────────────────────────────────────────────
// resolved functional-token map (prebuilt, per theme)
// ─────────────────────────────────────────────────────────────────────────

// Primer ships fully-resolved per-theme tokens at dist/docs/functional/themes/
// <theme>.json — a flat object keyed by the exact CSS-var name (no leading
// `--`) with `value` already resolved to a literal hex (no var()/ref chasing).
// Returns name -> hex; throws on a missing key (catches upstream renames).
function loadTokens(theme) {
  const tokens = JSON.parse(fs.readFileSync(path.join(DOCS, `${theme}.json`), 'utf8'))
  return (name) => {
    const t = tokens[name]
    if (!t || t.value === undefined) throw new Error(`missing token --${name} in ${theme}.json`)
    return t.value
  }
}

// ─────────────────────────────────────────────────────────────────────────
// generate
// ─────────────────────────────────────────────────────────────────────────

const norm = (hex) => hex.toLowerCase()

function buildPalette(t) {
  const tree = loadColorTree(t.base)
  const cssVar = loadTokens(t.theme)
  const p = {}

  // base00..07 from the neutral scale
  MONO_STEPS[t.variant].forEach((step, i) => {
    p[`base0${i}`] = norm(resolveColor(tree, `neutral.${step}`))
  })

  // accents
  for (const [slot, varName] of Object.entries(ACCENT_VARS)) {
    p[slot] = norm(cssVar(varName))
  }

  // base24 extra backgrounds: base10 near-black, base11 pure black
  p.base10 = norm(resolveColor(tree, 'black'))
  p.base11 = '#000000'

  return p
}

function toYaml(t, palette, slots) {
  const lines = [
    `system: "${t.system}"`,
    `name: "${t.name}"`,
    `author: "${AUTHOR}"`,
    `variant: "${t.variant}"`,
    'palette:',
    ...slots.map((s) => `  ${s}: "${palette[s]}"`),
  ]
  return HEADER + lines.join('\n') + '\n'
}

// ── Tinted8 build/emit ──────────────────────────────────────────────────────
const SOLID = /^#[0-9a-fA-F]{6}$/

function buildTinted8(t) {
  const cssVar = loadTokens(t.theme)
  // Resolve a dist token to a solid hex, or null (skip) if missing or alpha.
  const solid = (name) => {
    try { const v = cssVar(name); return SOLID.test(v) ? norm(v) : null } catch { return null }
  }
  const pick = (map) => {
    const out = {}
    for (const [k, v] of Object.entries(map)) { const h = solid(v); if (h) out[k] = h }
    return out
  }
  return { palette: pick(T8_PALETTE), syntax: pick(T8_SYNTAX), ui: pick(T8_UI) }
}

function toTinted8Yaml(t, name, slug, data) {
  const L = [
    'scheme:',
    '  system: "tinted8"',
    '  supports:',
    '    styling-spec: "0.2.0"',
    `  author: "${AUTHOR}"`,
    `  name: "${name}"`,
    `  slug: "${slug}"`,
    `variant: "${t.variant}"`,
  ]
  const section = (label, map, data) => {
    L.push(`${label}:`)
    for (const k of Object.keys(map)) if (data[k]) L.push(`  ${k}: "${data[k]}"`)
  }
  section('palette', T8_PALETTE, data.palette)
  section('syntax', T8_SYNTAX, data.syntax)
  section('ui', T8_UI, data.ui)
  return HEADER + L.join('\n') + '\n'
}

const OUT = (process.argv.find((a) => a.startsWith('--out='))?.split('=')[1]) || ROOT
// Optional filename/name suffix (e.g. --suffix=-test for A/B comparisons) and
// theme filter (e.g. --themes=github-dark,github-dark-dimmed).
const SUFFIX = (process.argv.find((a) => a.startsWith('--suffix='))?.split('=')[1]) || ''
const ONLY = (process.argv.find((a) => a.startsWith('--themes='))?.split('=')[1])?.split(',')

let written = 0
for (const t of THEMES) {
  if (ONLY && !ONLY.includes(t.file)) continue
  const palette = buildPalette(t)
  for (const system of ['base16', 'base24']) {
    const slots = system === 'base16' ? BASE16_SLOTS : BASE24_SLOTS
    // The light default is named "Github" in base16 but "Github Light" in base24,
    // matching the pre-existing files; every other scheme shares one name.
    let name = (system === 'base24' && t.theme === 'light') ? 'Github Light' : t.name
    if (SUFFIX) name += ` (${SUFFIX.replace(/^-/, '')})`
    const out = toYaml({ ...t, system, name }, palette, slots)
    const dir = path.join(OUT, system)
    fs.mkdirSync(dir, { recursive: true })
    fs.writeFileSync(path.join(dir, `${t.file}${SUFFIX}.yaml`), out)
    written++
  }

  // tinted8: palette<-ANSI, syntax<-prettylights, ui<-functional tokens
  let t8name = (t.theme === 'light') ? 'Github Light' : t.name
  if (SUFFIX) t8name += ` (${SUFFIX.replace(/^-/, '')})`
  const t8dir = path.join(OUT, 'tinted8')
  fs.mkdirSync(t8dir, { recursive: true })
  fs.writeFileSync(path.join(t8dir, `${t.file}${SUFFIX}.yaml`), toTinted8Yaml(t, t8name, `${t.file}${SUFFIX}`, buildTinted8(t)))
  written++
}
console.log(`[mode=${MODE}] ${written} files generated under ${OUT}`)
